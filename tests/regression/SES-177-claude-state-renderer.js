//
// Guards scripts/render-claude-state.js and the CLAUDE-STATE.md / standing-brief.md split.
//
// The predicates are IMPORTED from the real script rather than reimplemented, per John's rule
// 2026-08-23 ("you should never be throwing away tests") and the DIR-603f44ea / SES-176 precedent: a
// test that copies the logic it guards passes forever while the shipped file rots.
//
// THE ASSERTION THAT MATTERS is the fail-closed one, and it is exercised END-TO-END rather than by
// reading the source: the standing brief is moved aside, the real script is spawned, and the test
// asserts it exited 2 AND left CLAUDE-STATE.md byte-identical. That is the failure John named in his
// own decision ("the renderer must fail rather than regenerate a file that would lose the
// standing-brief link"), and it is the v7.0.197 briefing wipe in a second costume -- a rebuild from a
// source that does not cover the whole file, publishing a tidy skeleton over real content.
//
// It runs WITHOUT credentials on purpose: the fail-closed check in the script sits above the env
// check, so a machine with no Supabase keys still exercises the branch that protects the file.

import assert from "assert";
import fs from "fs";
import path from "path";
import { execFileSync } from "child_process";
import { fileURLToPath } from "url";
import { selfRun, notRun } from "./_lib/self-run.js";
import { bodyKeepsStandingLink, renderBullet, stripId, renderBody } from "../../scripts/render-claude-state.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const STATE = path.join(ROOT, "CLAUDE-STATE.md");
const BRIEF = path.join(ROOT, "docs/runbooks/standing-brief.md");
const SCRIPT = path.join(ROOT, "scripts/render-claude-state.js");
const LINK = "docs/runbooks/standing-brief.md";

// ---------------------------------------------------------------------------
// The split itself
// ---------------------------------------------------------------------------
function theStandingBriefExistsAndCarriesTheProse() {
  assert.ok(fs.existsSync(BRIEF), "docs/runbooks/standing-brief.md must exist -- it holds 53% of the old CLAUDE-STATE.md");
  const brief = fs.readFileSync(BRIEF, "utf8");
  const para = brief.split("\n").find(l => l.startsWith("**Next session:**"));
  assert.ok(para, "the standing brief must still carry the moved '**Next session:**' paragraph");
  assert.ok(para.length > 5000,
    `the standing paragraph is ${para?.length} chars; it was 7,643 at the move. A large drop means it was summarised, which is the one thing the move forbids.`);
}

function claudeStateLinksTheBriefAndIsGenerated() {
  const state = fs.readFileSync(STATE, "utf8");
  assert.ok(state.includes(LINK), "CLAUDE-STATE.md must link the standing brief");
  assert.ok(state.includes("GENERATED by scripts/render-claude-state.js"), "CLAUDE-STATE.md must carry the generated marker");
  assert.ok(state.length < 6000,
    `CLAUDE-STATE.md is ${state.length} chars. It was 14,355 before the split and its own charter says keep it short; past ~6k the split has quietly been undone.`);
}

// ---------------------------------------------------------------------------
// The fail-closed predicate -- with its negative control
// ---------------------------------------------------------------------------
function theLinkPredicateHasTeeth() {
  const good = fs.readFileSync(STATE, "utf8");
  assert.strictEqual(bodyKeepsStandingLink(good), true, "the real file must satisfy the predicate");

  const stripped = good.split(LINK).join("docs/runbooks/SOMETHING-ELSE.md");
  assert.notStrictEqual(stripped, good, "the mutation changed nothing -- the control is vacuous");
  assert.strictEqual(bodyKeepsStandingLink(stripped), false, "a body without the link must fail the predicate");
  assert.strictEqual(bodyKeepsStandingLink(""), false, "an empty body must fail the predicate");
  assert.strictEqual(bodyKeepsStandingLink(null), false, "a non-string must fail the predicate, not throw");
}

// ---------------------------------------------------------------------------
// END-TO-END: the script refuses, and writes nothing, when the brief is gone.
// ---------------------------------------------------------------------------
function theRendererRefusesWithoutTheStandingBrief() {
  const before = fs.readFileSync(STATE);
  const stash = BRIEF + ".test-stash";
  let exitCode = 0;
  let moved = false;
  try {
    fs.renameSync(BRIEF, stash);
    moved = true;
    try {
      execFileSync(process.execPath, [SCRIPT], { cwd: ROOT, stdio: "pipe" });
    } catch (e) {
      exitCode = e.status;
    }
  } finally {
    if (moved && fs.existsSync(stash)) fs.renameSync(stash, BRIEF);
  }
  assert.strictEqual(exitCode, 2, "a missing standing brief must exit 2 (could not run), never 0 and never a silent render");
  assert.ok(fs.readFileSync(STATE).equals(before), "CLAUDE-STATE.md must be byte-identical after the refusal -- refusing means writing nothing");
  assert.ok(fs.existsSync(BRIEF), "the test must restore the standing brief it moved");
}

// ---------------------------------------------------------------------------
// The render itself, on fixtures -- no network, no credentials.
// ---------------------------------------------------------------------------
const CY = (over = {}) => ({
  id: "aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee", started_at: "2026-08-24T16:38:03Z",
  trigger: "chained (drain continuation)", model: "claude-opus-5",
  version: "v7.0.227", item_id: "SES-158", push_sha: "f4b4004", ...over,
});

// The design decision an editor would collapse: the VERSION lines skip version-less cycles, the
// BULLETS do not. Asserted with a fixture where the newest shipped cycle claimed no version.
function versionLinesSkipVersionlessCyclesButBulletsDoNot() {
  const cycles = [
    CY({ id: "11111111-0000-0000-0000-000000000000", version: null, item_id: "SES-188" }),
    CY({ id: "22222222-0000-0000-0000-000000000000", version: "v7.0.227", item_id: "SES-158" }),
    CY({ id: "33333333-0000-0000-0000-000000000000", version: "v7.0.225", item_id: "SES-155" }),
  ];
  const body = renderBody(cycles, new Map());

  const verLine = body.split("\n").find(l => l.startsWith("**Version in dev:**"));
  const priorLine = body.split("\n").find(l => l.startsWith("**Prior:**"));
  assert.ok(verLine.includes("v7.0.227"),
    "Version in dev must be the newest cycle that CLAIMED a version; taking cycles[0] renders '(no version claimed)' as the version of dev, which answers the wrong question");
  assert.ok(!verLine.includes("no version claimed"), "Version in dev must never render the placeholder");
  assert.ok(priorLine.includes("v7.0.225"), "Prior must be the next versioned cycle back");

  // ...and the version-less cycle is still listed as a session that happened.
  assert.ok(body.includes("11111111"), "a version-less shipped cycle must still appear in the session bullets");
  assert.ok(body.includes("SES-188"), "its ticket must still appear");
}

function aCycleWithNoShipCardRendersWithoutInventingASummary() {
  const body = renderBody([CY({ item_id: "SES-999" })], new Map());
  assert.ok(body.includes("SES-999"), "the ticket id must render");
  assert.ok(!/undefined|null/.test(body), "a missing card must not leak 'undefined'/'null' into the file");
}

function theIdIsNotStutteredWhenTheCardTitleAlreadyCarriesIt() {
  assert.strictEqual(stripId("SES-158 — Vision comment routing", "SES-158"), "Vision comment routing");
  assert.strictEqual(stripId("Vision comment routing", "SES-158"), "Vision comment routing", "a title without the id prefix is untouched");
  const bullet = renderBullet(CY(), { title: "SES-158 — Vision comment routing", plain_after: "It routes.", plain_worth: "It helps." });
  assert.ok(!/SES-158.*SES-158/.test(bullet), "the ticket id must appear once, not twice");
  assert.ok(bullet.includes("It routes."), "the card's plain-language summary must reach the bullet");
}

function renderIsPureAndDeterministic() {
  const cycles = [CY()];
  assert.strictEqual(renderBody(cycles, new Map()), renderBody(cycles, new Map()), "the same input must render the same bytes");
}

// The credentialed half: --check against the live ledger. Declared, never inferred (SES-180 (b)).
function checkModeAgreesWithTheCommittedFile() {
  if (!process.env.SUPABASE_URL || !process.env.SUPABASE_SERVICE_KEY) {
    notRun("render-claude-state --check against the live ledger",
      "SUPABASE_URL / SUPABASE_SERVICE_KEY are not set here; the offline assertions above still ran");
    return;
  }
  let code = 0;
  try {
    execFileSync(process.execPath, [SCRIPT, "--check"], { cwd: ROOT, stdio: "pipe" });
  } catch (e) {
    code = e.status;
  }
  assert.strictEqual(code, 0, "the committed CLAUDE-STATE.md must match what the ledger renders (exit 1 = drift, 2 = could not run)");
}

function run() {
  theStandingBriefExistsAndCarriesTheProse();
  claudeStateLinksTheBriefAndIsGenerated();
  theLinkPredicateHasTeeth();
  theRendererRefusesWithoutTheStandingBrief();
  versionLinesSkipVersionlessCyclesButBulletsDoNot();
  aCycleWithNoShipCardRendersWithoutInventingASummary();
  theIdIsNotStutteredWhenTheCardTitleAlreadyCarriesIt();
  renderIsPureAndDeterministic();
  checkModeAgreesWithTheCommittedFile();
}

selfRun(import.meta.url, run);
export default run;
