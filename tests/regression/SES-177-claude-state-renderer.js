const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const STATE = path.join(ROOT, "CLAUDE-STATE.md");
const BRIEF = path.join(ROOT, "docs/runbooks/standing-brief.md");
const SCRIPT = path.join(ROOT, "scripts/render-claude-state.js");
const LINK = "docs/runbooks/standing-brief.md";

// ---------------------------------------------------------------------------
// The split itself
// ---------------------------------------------------------------------------
function theStandingBriefExistsAndCarriesTheProse() {
  assert.ok(fs.existsSync(BRIEF), "docs/runbooks/standing-brief.md must exist -- it holds 53% of the old CLAUDE-STATE.md");
  const brief = fs.readFileSync(BRIEF, "utf8");
  const para = brief.split("\n").find(l => l.startsWith("**Next session:**"));
  assert.ok(para, "the standing brief must still carry the moved '**Next session:**' paragraph");
  assert.ok(para.length > 5000,
    `the standing paragraph is ${para?.length} chars; it was 7,643 at the move. A large drop means it was summarised, which is the one thing the move forbids.`);
}

function claudeStateLinksTheBriefAndIsGenerated() {
  const state = fs.readFileSync(STATE, "utf8");
  assert.ok(state.includes(LINK), "CLAUDE-STATE.md must link the standing brief");
  assert.ok(state.includes("GENERATED by scripts/render-claude-state.js"), "CLAUDE-STATE.md must carry the generated marker");
  assert.ok(state.length < 6000,
    `CLAUDE-STATE.md is ${state.length} chars. It was 14,355 before the split and its own charter says keep it short; past ~6k the split has quietly been undone.`);
}

// ---------------------------------------------------------------------------
// The fail-closed predicate -- with its negative control
// ---------------------------------------------------------------------------
function theLinkPredicateHasTeeth() {
  const good = fs.readFileSync(STATE, "utf8");
  assert.strictEqual(bodyKeepsStandingLink(good), true, "the real file must satisfy the predicate");

  const stripped = good.split(LINK).join("docs/runbooks/SOMETHING-ELSE.md");
  assert.notStrictEqual(stripped, good, "the mutation changed nothing -- the control is vacuous");
  assert.strictEqual(bodyKeepsStandingLink(stripped), false, "a body without the link must fail the predicate");
  assert.strictEqual(bodyKeepsStandingLink(""), false, "an empty body must fail the predicate");
  assert.strictEqual(bodyKeepsStandingLink(null), false, "a non-string must fail the predicate, not throw");
}

// ---------------------------------------------------------------------------
// END-TO-END: the script refuses, and writes nothing, when the brief is gone.
// ---------------------------------------------------------------------------
function theRendererRefusesWithoutTheStandingBrief() {
  const before = fs.readFileSync(STATE);
  const stash = BRIEF + ".test-stash";
  let exitCode = 0;
  let moved = false;
  try {
    fs.renameSync(BRIEF, stash);
    moved = true;
    try {
      execFileSync(process.execPath, [SCRIPT], { cwd: ROOT, stdio: "pipe" });
    } catch (e) {
      exitCode = e.status;
    }
  } finally {
    if (moved && fs.existsSync(stash)) fs.renameSync(stash, BRIEF);
  }
  assert.strictEqual(exitCode, 2, "a missing standing brief must exit 2 (could not run), never 0 and never a silent render");
  assert.ok(fs.readFileSync(STATE).equals(before), "CLAUDE-STATE.md must be byte-identical after the refusal -- refusing means writing nothing");
  assert.ok(fs.existsSync(BRIEF), "the test must restore the standing brief it moved");
}

