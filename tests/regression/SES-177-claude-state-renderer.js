// SES-381 — the retired whole-file bar and the retargeted skeleton clause must DISAGREE on a verbose
// render (direction 1) and AGREE on a re-inlined standing paragraph (direction 2). A clause that only
// passed the live file would be satisfied by a predicate that is always true.
function theSizeClauseMeasuresTheSplitNotTheLedger() {
  // Direction 1 — verbose ship cards blow past the retired bar and must NOT trip the new clause.
  const rows = Array.from({ length: 10 }, (_, i) =>
    CY({ id: `${i}${i}${i}${i}${i}${i}${i}${i}-0000-4000-8000-00000000000${i}`, item_id: "SES-381" }));
  // Keyed on the three RENDERED cycle ids, not the ticket (AGT-191): `renderBody` looks a card up by
  // `cycle.id` now, and rows 1-3 are the only ones that become bullets.
  const verbose = { title: "SES-381 — x", plain_after: "a".repeat(3000), plain_worth: "b".repeat(2000) };
  const cards = new Map(rows.slice(0, 3).map(r => [r.id, verbose]));
  const big = renderBody(rows, cards);
  assert.ok(big.length >= 6000,
    `the fixture must exceed the retired bar — otherwise this control proves nothing (it is ${big.length} chars)`);
  assert.ok(skeletonChars(big) < 3000,
    `verbose ship cards must NOT trip the clause; the fixture's skeleton is ${skeletonChars(big)} chars`);

  // Direction 2 — put the moved standing paragraph back and BOTH forms must fail: the guard has teeth.
  const state = fs.readFileSync(STATE, "utf8");
  const para = fs.readFileSync(BRIEF, "utf8").split("\n").find(l => l.startsWith("**Next session:**"));
  assert.ok(para, "the standing brief must carry the '**Next session:**' paragraph for this control to mean anything");
  const undone = state.replace("## Last 3 sessions", para + "\n\n## Last 3 sessions");
  assert.notStrictEqual(undone, state, "the mutation changed nothing -- the control is vacuous");
  assert.ok(skeletonChars(undone) >= 3000,
    `a re-inlined standing paragraph must trip the clause; the mutated skeleton is ${skeletonChars(undone)} chars`);
  assert.ok(undone.includes("**Next session:**"), "the string clause must see the re-inlined paragraph");
}

