// DeepBench v7.0.877 | scripts/sync-model-pricing.js | AGT-304 slice 17 -- the shared/models.js
// MODEL_PRICING block is GENERATED from public.model_pricing, so the two halves §19t requires to
// agree cannot drift again by hand.
//
// WHY THIS EXISTS, measured not recalled. public.model_pricing held 30 rows while MODEL_PRICING
// held 24; the six `claude-3-*` rows model-watch's catalog step wrote on 2026-10-12
// (docs/runbooks/model-watch-routine.md:72, apply_model_assignment()) were missing from the JS
// half, and LOG-149 part (e) -- re-run by agt-142 and agt-145 -- went red on the first of them.
// That was the THIRD time the same drift landed (slice 3 v7.0.778, slice 13 v7.0.822, both closed
// by hand-typing the new rows). A third hand-typed catch-up would buy the same week of quiet, so
// the block stops being hand-kept: SQL stays the written home, the JS block is rendered from it,
// and `--check` is the mechanical guard that makes a fourth drift a red line instead of a surprise
// (pattern:10 -- after two failed instruction-level guards, go structural; pattern:16 -- tracking
// systems must be self-maintaining; pattern:26 -- build the check that catches the whole class).
//
// CACHE-READ RATES ARE NOT IN SQL. public.model_pricing has no cache-read column, so the handful of
// published per-model cache rates stay JS-side in CACHE_READ_PER_1K (in the target file) and this
// generator merges them into the rows it renders. The map is imported FROM THE TARGET FILE rather
// than held here, so there is exactly one home for those rates and `--check` compares the file
// against a body derived from the file's own map (pattern:14 -- one shared core, not two copies).
//
// Usage:
//   node scripts/sync-model-pricing.js --check [--file=shared/models.js]
//   node scripts/sync-model-pricing.js --write [--file=shared/models.js]
//
// Exit codes: 0 in sync / written, 1 out of sync (--check only), 2 could not ask the question
// (no SUPABASE_URL / SUPABASE_SERVICE_KEY, or the read did not come back ok). EXIT 2 IS NEVER
// GREEN and never 1: "I could not look" is a different answer from "I looked and it is wrong", and
// collapsing them into a pass is how a credential-less cycle would report a clean mirror it never
// checked.

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_FILE = "shared/models.js";

// The markers are exported because the test and the generator must agree on them byte-for-byte; a
// second copy of either string in a test file is the drift this script exists to remove.
export const MARK_BEGIN = "  // BEGIN model_pricing mirror -- generated by scripts/sync-model-pricing.js --write; edit public.model_pricing, never this block";
export const MARK_END = "  // END model_pricing mirror";

// Pure. One rendered row. Numbers go through Number() then String() so the rendered text is a
// function of the VALUE, not of however PostgREST spelled it ("0.010" and 0.01 render identically)
// -- otherwise a harmless formatting change in the API response would read as drift.
function row(r, cache) {
  const parts = [
    `input_per_1k: ${String(Number(r.input_per_1k))}`,
    `output_per_1k: ${String(Number(r.output_per_1k))}`,
  ];
  if (cache != null) parts.push(`cache_read_per_1k: ${String(Number(cache))}`);
  return `  ${JSON.stringify(r.model)}: { ${parts.join(", ")} },\n`;
}

// Pure. Sorted by model id code point so the rendered block is STABLE and diffable: PostgREST row
// order is not a contract, and an unsorted render would produce a different file on every run
// (pattern:3 -- reproducible output beats convenient implementation).
export function renderRows(rows, cacheRates = {}) {
  return [...rows]
    .sort((a, b) => (a.model === b.model ? 0 : a.model < b.model ? -1 : 1))
    .map(r => row(r, cacheRates[r.model]))
    .join("");
}

// Both marker lookups fail LOUDLY and name WHICH marker was wrong. A missing marker means someone
// edited the generated block's fences; silently re-adding them would let the generator overwrite
// hand-written code it never bounded.
function bounds(src) {
  for (const [name, mark] of [["BEGIN", MARK_BEGIN], ["END", MARK_END]]) {
    const first = src.indexOf(mark);
    if (first === -1) throw new Error(`${name} marker not found: the target file must contain the ${name} marker line exactly once`);
    if (src.indexOf(mark, first + 1) !== -1) throw new Error(`${name} marker found more than once: the target file must contain the ${name} marker line exactly once`);
  }
  const i = src.indexOf(MARK_BEGIN) + MARK_BEGIN.length;
  const j = src.indexOf(MARK_END);
  if (j < i) throw new Error("END marker precedes the BEGIN marker: the generated block is inside out");
  return { i, j };
}

// Pure. The generated body, exactly as renderRows() produced it: the single newline that ends the
// BEGIN marker's own line belongs to the fence, not to the body, so it is dropped here and put back
// by spliceBlock(). That is what makes blockOf(spliceBlock(src, body)) === body hold.
export function blockOf(src) {
  const { i, j } = bounds(src);
  const raw = src.slice(i, j);
  return raw.startsWith("\n") ? raw.slice(1) : raw;
}

// Pure. `src` with the generated body replaced. Everything outside the fences -- the header
// comments, CACHE_READ_PER_1K, computeCallCost(), every other export -- is carried through
// untouched; this script writes the rows and nothing else.
export function spliceBlock(src, body) {
  const { i, j } = bounds(src);
  return src.slice(0, i) + "\n" + body + src.slice(j);
}

// Pure. The human-readable account of a drift, by id. Rates compare at 1e-9 because both halves
// store decimal dollars that round-trip through JSON: an exact === would call 0.003 and 0.003
// different the day one side arrives as a string.
export function diffPricing(rows, table) {
  const near = (a, b) => Math.abs(Number(a) - Number(b)) < 1e-9;
  const missing = [], disagree = [];
  const sqlIds = new Set();
  for (const r of rows) {
    sqlIds.add(r.model);
    const js = table[r.model];
    if (!js) { missing.push(r.model); continue; }
    if (!near(r.input_per_1k, js.input_per_1k) || !near(r.output_per_1k, js.output_per_1k)) disagree.push(r.model);
  }
  const extra = Object.keys(table).filter(id => !sqlIds.has(id));
  return { missing, extra, disagree };
}

// --- CLI ---------------------------------------------------------------------------------------

function die2(message) {
  console.error(`model_pricing mirror: ${message}`);
  console.error("  exit 2 -- could not check. This is NOT a pass; export SUPABASE_URL and SUPABASE_SERVICE_KEY (runner_secrets by name) and run again.");
  process.exit(2);
}

async function fetchPricing() {
  const url = process.env.SUPABASE_URL, key = process.env.SUPABASE_SERVICE_KEY;
  if (!url || !key) die2("SUPABASE_URL / SUPABASE_SERVICE_KEY not set");
  let r;
  try {
    r = await fetch(`${url}/rest/v1/model_pricing?select=model,input_per_1k,output_per_1k`, {
      headers: { apikey: key, Authorization: `Bearer ${key}` },
    });
  } catch (e) {
    die2(`read of public.model_pricing failed: ${e.message}`);
  }
  if (!r.ok) die2(`read of public.model_pricing returned HTTP ${r.status} ${await r.text().catch(() => "")}`);
  const rows = await r.json().catch(() => null);
  if (!Array.isArray(rows)) die2("read of public.model_pricing did not return a row array");
  return rows;
}

async function main(argv) {
  const mode = argv.includes("--write") ? "write" : argv.includes("--check") ? "check" : null;
  if (!mode) {
    console.error("usage: node scripts/sync-model-pricing.js --check|--write [--file=shared/models.js]");
    process.exit(2);
  }
  const fileArg = (argv.find(a => a.startsWith("--file=")) || "").slice("--file=".length);
  const target = path.resolve(ROOT, fileArg || DEFAULT_FILE);

  const rows = await fetchPricing();
  const src = fs.readFileSync(target, "utf8");
  // The cache-read map and the current table come from the TARGET file, so --file=<tmp> checks that
  // copy against its own map rather than against the repo's.
  const mod = await import(`${new URL(`file://${target}`).href}?t=${Date.now()}`);
  const cacheRates = mod.CACHE_READ_PER_1K || {};
  const body = renderRows(rows, cacheRates);

  if (mode === "write") {
    fs.writeFileSync(target, spliceBlock(src, body));
    console.log(`model_pricing mirror: ${rows.length} rows written`);
    process.exit(0);
  }

  if (blockOf(src) === body) {
    console.log(`model_pricing mirror: ${rows.length} rows, in sync`);
    process.exit(0);
  }
  const { missing, extra, disagree } = diffPricing(rows, mod.MODEL_PRICING || {});
  for (const id of missing) console.log(`missing in JS: ${id}`);
  for (const id of extra) console.log(`extra in JS: ${id}`);
  for (const id of disagree) console.log(`rates disagree: ${id}`);
  // A block that holds the right ids at the right rates but not the generated TEXT is still out of
  // sync -- the file is no longer what --write produces, so the next --write would move it. Saying
  // nothing here would print a bare `Fix:` with no reason above it.
  if (!missing.length && !extra.length && !disagree.length) {
    console.log("block text differs from the generated form (ids and rates agree; order, spacing or a hand edit does not)");
  }
  console.log("Fix: node scripts/sync-model-pricing.js --write");
  process.exit(1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  main(process.argv.slice(2)).catch(e => { console.error(`model_pricing mirror: ${e.message}`); process.exit(1); });
}
