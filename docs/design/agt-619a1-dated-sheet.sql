-- DeepBench v7.0.1112 | docs/design/agt-619a1-dated-sheet.sql | AGT-619 stage A1 of three applies -- public.model_pricing becomes a dated sheet with a row id and its own cache-read rate
--
-- THE MIRROR of migration `agt619a1_dated_sheet`. Everything below the VERBATIM marker is the
-- migration as designed (kickoff docs/kickoffs/v7.0.1112-AGT-619-each-dollar-names-its-rate-staged.md).
--
-- WHAT CHANGES (additive; no row is rewritten except the two cache-rate seeds)
--   1. public.model_pricing  + id (identity, unique), cache_read_per_1k, effective_from, retired_at.
--      The two published cache-read rates move here from shared/models.js CACHE_READ_PER_1K.
--   2. public.model_pricing_date_rate()  NEW trigger function + trigger: a rate change on a row
--      moves that row's effective_from to now(), so the date is true after an in-place rate write
--      (public.apply_model_assignment() updates rates in place and is NOT touched here).
-- REACH: 30 rows of a table only postgres and service_role read. No public grant, no ledger row.
-- NOT TOUCHED: model_pricing's primary key (model), model_catalog's foreign key to it, every
-- function body, public.ai_activity_log (stage A2).
--
-- DOWN. Before the apply: public.capture_migration_down(<cycle>, 'agt619a1_dated_sheet', the three
-- NEW objects) -- its down removes the unique constraint, the trigger and the function and leaves
-- the four columns standing, inert. Removing the columns is attended-only:
--   alter table public.model_pricing drop column retired_at, drop column effective_from,
--     drop column cache_read_per_1k, drop column id;
-- Guard: tests/regression/agt-619-rate-lineage.test.mjs. Governing: docs/ARCHITECTURE.md section 19t.
--
-- ---- THE MIGRATION, VERBATIM ---
alter table public.model_pricing
  add column id bigint generated by default as identity,
  add column cache_read_per_1k numeric check (cache_read_per_1k is null or cache_read_per_1k >= 0),
  add column effective_from timestamptz not null default now(),
  add column retired_at timestamptz;

alter table public.model_pricing add constraint model_pricing_id_key unique (id);

comment on column public.model_pricing.id is 'AGT-619: the rate row''s id; ai_activity_log.pricing_row_id names it.';
comment on column public.model_pricing.cache_read_per_1k is 'AGT-619: the model''s own published cache-read rate per 1k tokens; NULL = 0.10 x input_per_1k.';
comment on column public.model_pricing.effective_from is 'AGT-619: the instant this row''s rates took effect. Rows that predate v7.0.1112 carry the instant the sheet began keeping dates.';
comment on column public.model_pricing.retired_at is 'AGT-619: the instant this row stopped pricing new calls; NULL = in force.';

-- The two published per-model cache-read rates, moved from shared/models.js CACHE_READ_PER_1K.
update public.model_pricing set cache_read_per_1k = 0.00025 where model = 'claude-fable-5-1';
update public.model_pricing set cache_read_per_1k = 0.0002  where model = 'claude-opus-5-5';

create or replace function public.model_pricing_date_rate()
 returns trigger
 language plpgsql
 set search_path to 'public', 'pg_catalog'
as $function$
begin
  -- AGT-619 (v7.0.1112). A row's effective_from is the instant its CURRENT rates took effect, so a
  -- rate written in place moves it. A ledger row stamped with this row's id and created before
  -- effective_from was therefore priced at a rate this row no longer holds -- countable, never silent.
  if (new.input_per_1k, new.output_per_1k, new.cache_read_per_1k)
     is distinct from (old.input_per_1k, old.output_per_1k, old.cache_read_per_1k) then
    new.effective_from := now();
  end if;
  return new;
end
$function$;

revoke all on function public.model_pricing_date_rate() from public, anon, authenticated;

create trigger model_pricing_date_rate
  before update on public.model_pricing
  for each row execute function public.model_pricing_date_rate();

do $gate$
declare
  n integer;
begin
  -- A1 GATE 1: the four columns exist.
  select count(*) into n from information_schema.columns
   where table_schema = 'public' and table_name = 'model_pricing'
     and column_name in ('id', 'cache_read_per_1k', 'effective_from', 'retired_at');
  if n <> 4 then raise exception 'A1 GATE 1: % of 4 columns exist', n; end if;

  -- A1 GATE 2: every sheet row has its own id and a date; exactly the two seeded cache rates.
  select count(*) into n from public.model_pricing where id is null or effective_from is null;
  if n <> 0 then raise exception 'A1 GATE 2: % sheet row(s) lack an id or a date', n; end if;
  select count(*) - count(distinct id) into n from public.model_pricing;
  if n <> 0 then raise exception 'A1 GATE 2: % duplicate sheet id(s)', n; end if;
  select count(*) into n from public.model_pricing
   where (model = 'claude-fable-5-1' and cache_read_per_1k = 0.00025)
      or (model = 'claude-opus-5-5' and cache_read_per_1k = 0.0002);
  if n <> 2 then raise exception 'A1 GATE 2: % of 2 cache-read rates seeded', n; end if;
  select count(*) into n from public.model_pricing where cache_read_per_1k is not null;
  if n <> 2 then raise exception 'A1 GATE 2: % rows carry a cache-read rate, expected 2', n; end if;

  -- A1 GATE 3: the sheet stays closed to the public key, and so does the trigger function.
  if has_table_privilege('anon', 'public.model_pricing', 'select')
     or has_any_column_privilege('anon', 'public.model_pricing', 'select')
     or has_table_privilege('authenticated', 'public.model_pricing', 'select')
     or has_any_column_privilege('authenticated', 'public.model_pricing', 'select') then
    raise exception 'A1 GATE 3: model_pricing is readable by anon or authenticated';
  end if;
  if has_function_privilege('anon', 'public.model_pricing_date_rate()', 'execute')
     or has_function_privilege('authenticated', 'public.model_pricing_date_rate()', 'execute') then
    raise exception 'A1 GATE 3: model_pricing_date_rate() is executable by anon or authenticated';
  end if;
end
$gate$;
